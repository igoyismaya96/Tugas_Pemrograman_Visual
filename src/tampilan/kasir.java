   protected void datatable(){
    Object[] Baris = {"ID kasir", "Nama Kasir", "Jenis Kelamin", "Agama", "No Telephon", "Alamat", "Password"};
    tabmode = new DefaultTableModel(null, Baris);
    tblbarang.setModel(tabmode);

    String cari = txtcari.getText();

    try{
        String sql;
        PreparedStatement stat;

        if (cari.equals("")) {
            sql = "SELECT * FROM kasir";
            stat = conn.prepareStatement(sql);
        } else {
            sql = "SELECT * FROM kasir WHERE nm_kasir LIKE ? OR jenis_kelamin LIKE ?";
            stat = conn.prepareStatement(sql);
            stat.setString(1, "%" + cari + "%");
            stat.setString(2, "%" + cari + "%");
        }

        ResultSet hasil = stat.executeQuery();

        while(hasil.next()){
            String a = hasil.getString("id_kasir");
            String b = hasil.getString("nm_kasir");
            String c = hasil.getString("jenis_kelamin");
            String d = hasil.getString("no_telephon");
            String e = hasil.getString("agama");
            String f = hasil.getString("alamat");
            String g = hasil.getString("password");

            String[] data = {a,b,c,d,e,f,g};
            tabmode.addRow(data);
        }

    } catch (Exception f){
        JOptionPane.showMessageDialog(null, f);
    }
}
