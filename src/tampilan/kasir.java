private void autoID() {
    try {
        String sql = "SELECT MAX(id_kasir) FROM kasir";
        Statement stat = conn.createStatement();
        ResultSet rs = stat.executeQuery(sql);

        if (rs.next()) {
            String max_id = rs.getString(1);

            if (max_id == null) {
                txtid.setText("KSR001");
            } else {
                int num = Integer.parseInt(max_id.substring(3)); // karena "BRG"
                num++;
                txtid.setText(String.format("KSR%03d", num));
            }
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Auto ID error: " + e);
    }
}   
